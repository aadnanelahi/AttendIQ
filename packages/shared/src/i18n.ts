export function translate(locale: Locale, key: I18nKey): string {
  if (locale === 'ar') return ar[key] ?? en[key];
  return en[key];
}

export function localeFromString(value: string | null | undefined): Locale {
  return value?.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}